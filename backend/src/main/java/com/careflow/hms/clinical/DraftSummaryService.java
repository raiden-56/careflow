/**
 * Deterministic "AI-assist" draft summaries ({@value #GENERATOR}). Every statement is assembled from
 * existing records and carries references to its sources; nothing is inferred or invented. Drafts are
 * never part of the record until a clinician accepts them (which creates a note authored by that
 * clinician) - or they are rejected.
 */
@Service
@RequiredArgsConstructor
public class DraftSummaryService {

    public static final String GENERATOR = "rule-based-summarizer-v1";
    public static final String DISCLAIMER = "DRAFT generated by " + GENERATOR + " from existing records only - no external AI service "
            + "is used and nothing is inferred. Verify each statement against its linked source before accepting.";

    private final AiDraftRepository drafts;
    private final DiagnosisRepository diagnoses;
    private final TreatmentPlanRepository plans;
    private final VitalSignRepository vitalsRepo;
    private final ClinicalAlertRepository alerts;
    private final LabOrderRepository labOrders;
    private final LabResultRepository labResults;
    private final ClinicalNoteRepository notes;
    private final CareTaskRepository tasks;
    private final MedicationOrderRepository medOrders;
    private final MedicationRepository medications;
    private final MedicationAdministrationRepository administrations;
    private final ClinicalRecordService records;
    private final ClinicalSupport support;
    private final AuditService audit;

    private final class Builder {
        final List<String> lines = new ArrayList<>();
        final List<Map<String, Object>> refs = new ArrayList<>();

        void add(String statement, List<Map<String, Object>> sources) {
            Map<String, Object> m = new LinkedHashMap<>();
            m.put("index", lines.size());
            m.put("statement", statement);
            m.put("sources", sources);
            lines.add(statement);
            refs.add(m);
        }
    }

    private static Map<String, Object> src(String type, UUID id, String label, Instant at) {
        Map<String, Object> m = new LinkedHashMap<>();
        m.put("type", type);
        m.put("id", id == null ? null : id.toString());
        m.put("label", label);
        m.put("at", at == null ? null : at.toString());
        return m;
    }

    @Transactional
    public DraftView generate(UUID admissionId, AiDraft.DraftType type) {
        Admission a = support.requireOpenClinical(admissionId);
        if (type != AiDraft.DraftType.PROGRESS_SUMMARY && type != AiDraft.DraftType.HANDOVER) {
            throw ApiException.badRequest("UNSUPPORTED_DRAFT", "Only progress and handover summaries are supported.");
        }
        Builder b = new Builder();
        build(a, type, b);
        if (b.lines.isEmpty()) {
            throw ApiException.rule("NOTHING_TO_SUMMARISE", "There are no records to summarise yet.");
        }
        AiDraft d = new AiDraft();
        d.setAdmissionId(a.getId());
        d.setDraftType(type);
        d.setGenerator(GENERATOR);
        d.setContent(b.lines.stream().map(l -> "- " + l).collect(Collectors.joining("\n")));
        d.setSourceRefs(b.refs);
        d.setStatus(AiDraft.Status.DRAFT);
        d.setCreatedBy(TenantContext.actorId());
        d.setCreatedAt(Instant.now());
        d = drafts.saveAndFlush(d);
        audit.record("DRAFT_GENERATED", "AI_DRAFT", d.getId(), a.getPatientId(), type + " via " + GENERATOR);
        return view(d);
    }

    private void build(Admission a, AiDraft.DraftType type, Builder b) {
        ZoneId zone = TimeUtil.zone();
        DateTimeFormatter f = DateTimeFormatter.ofPattern("dd MMM HH:mm").withZone(zone);
        Instant now = Instant.now();
        Instant day = now.minus(Duration.ofHours(24));

        b.add("Admitted " + f.format(a.getAdmittedAt()) + " (" + a.getAdmissionType().name().toLowerCase() + ") under "
                        + support.userName(a.getAttendingDoctorId()) + ": " + ClinicalSupport.truncate(a.getAdmissionReason(), 200),
                List.of(src("ADMISSION", a.getId(), a.getAdmissionNumber(), a.getAdmittedAt())));

        diagnoses.findByAdmissionIdOrderByRecordedAtDesc(a.getId()).stream()
                .filter(d -> d.getStatus() == Diagnosis.Status.ACTIVE).limit(4)
                .forEach(d -> b.add((d.isPrimary() ? "Primary diagnosis" : "Diagnosis") + " (" + d.getDiagnosisType().name().toLowerCase() + "): "
                                + d.getDescription() + (d.getIcdCode() != null ? " [" + d.getIcdCode() + "]" : ""),
                        List.of(src("DIAGNOSIS", d.getId(), d.getDescription(), d.getRecordedAt()))));

        if (type == AiDraft.DraftType.PROGRESS_SUMMARY) {
            plans.findByAdmissionIdAndStatus(a.getId(), TreatmentPlan.Status.ACTIVE).ifPresent(p ->
                    b.add("Active treatment plan v" + p.getPlanVersion() + " goals: " + ClinicalSupport.truncate(p.getGoals(), 300),
                            List.of(src("TREATMENT_PLAN", p.getId(), "Plan v" + p.getPlanVersion(), p.getCreatedAt()))));
        }

        List<VitalSign> recent = vitalsRepo.findByAdmissionIdAndEnteredInErrorFalseAndRecordedAtBetweenOrderByRecordedAtAsc(
                a.getId(), now.minus(Duration.ofHours(48)), now);
        if (!recent.isEmpty()) {
            VitalSign last = recent.get(recent.size() - 1);
            b.add("Latest observations (" + f.format(last.getRecordedAt()) + "): " + VitalsService.describe(last),
                    List.of(src("VITAL_SIGN", last.getId(), "Observation set", last.getRecordedAt())));
            for (VitalsService.Param p : List.of(VitalsService.Param.TEMPERATURE_C, VitalsService.Param.PULSE_BPM,
                    VitalsService.Param.SPO2, VitalsService.Param.SYSTOLIC_BP)) {
                List<VitalSign> cur = recent.stream().filter(v -> v.getRecordedAt().isAfter(day) && p.extract.apply(v) != null).toList();
                List<VitalSign> prev = recent.stream().filter(v -> !v.getRecordedAt().isAfter(day) && p.extract.apply(v) != null).toList();
                if (cur.size() >= 2 && !prev.isEmpty()) {
                    BigDecimal m1 = VitalsService.stats(cur.stream().map(p.extract).toList()).mean();
                    BigDecimal m0 = VitalsService.stats(prev.stream().map(p.extract).toList()).mean();
                    List<Map<String, Object>> s = new ArrayList<>();
                    cur.forEach(v -> s.add(src("VITAL_SIGN", v.getId(), p.label, v.getRecordedAt())));
                    prev.forEach(v -> s.add(src("VITAL_SIGN", v.getId(), p.label, v.getRecordedAt())));
                    b.add(p.label + " mean " + m1.toPlainString() + " " + p.unit + " over the last 24 h (" + cur.size()
                            + " readings) vs " + m0.toPlainString() + " " + p.unit + " in the previous 24 h (" + prev.size() + " readings)", s);
                }
            }
        } else {
            b.add("No observations recorded in the last 48 hours", List.of(src("VITAL_SIGN", null, "No records", null)));
        }

        List<ClinicalAlert> alertList = alerts.findByAdmissionIdOrderByRaisedAtDesc(a.getId());
        List<ClinicalAlert> unresolved = alertList.stream().filter(x -> x.getStatus() != ClinicalAlert.Status.RESOLVED).toList();
        long recentAlerts = alertList.stream().filter(x -> x.getRaisedAt().isAfter(day)).count();
        if (!unresolved.isEmpty() || recentAlerts > 0) {
            b.add(recentAlerts + " alert(s) raised in the last 24 h; " + unresolved.size() + " unresolved"
                            + (unresolved.isEmpty() ? "" : ": " + unresolved.stream().limit(3).map(ClinicalAlert::getTitle).collect(Collectors.joining("; "))),
                    alertList.stream().filter(x -> x.getRaisedAt().isAfter(day) || x.getStatus() != ClinicalAlert.Status.RESOLVED).limit(10)
                            .map(x -> src("CLINICAL_ALERT", x.getId(), x.getTitle(), x.getRaisedAt())).toList());
        }

        List<LabOrder> orders = labOrders.findByAdmissionIdOrderByOrderedAtDesc(a.getId());
        Map<UUID, List<LabResult>> res = labResults.findByLabOrderIdIn(orders.stream().map(LabOrder::getId).toList()).stream()
                .collect(Collectors.groupingBy(LabResult::getLabOrderId));
        orders.stream().filter(o -> (o.getStatus() == LabOrder.Status.RESULTED || o.getStatus() == LabOrder.Status.REVIEWED))
                .filter(o -> res.getOrDefault(o.getId(), List.of()).stream().anyMatch(r -> r.getResultedAt().isAfter(now.minus(Duration.ofHours(72)))))
                .limit(5).forEach(o -> {
                    List<LabResult> rs = res.getOrDefault(o.getId(), List.of());
                    String abn = rs.stream().filter(r -> r.getFlag() != LabResult.Flag.NORMAL)
                            .map(r -> r.getComponent() + " " + r.getValueText() + (r.getUnit() != null ? " " + r.getUnit() : "")
                                    + " (" + r.getFlag().name().toLowerCase().replace('_', ' ') + ")")
                            .collect(Collectors.joining(", "));
                    b.add(o.getTestName() + " " + (o.getStatus() == LabOrder.Status.REVIEWED ? "(reviewed)" : "(awaiting review)") + ": "
                                    + (abn.isEmpty() ? "all reported components within reference range" : abn),
                            List.of(src("LAB_ORDER", o.getId(), o.getOrderNumber(), o.getOrderedAt())));
                });
        List<LabOrder> pending = orders.stream().filter(o -> EnumSet.of(LabOrder.Status.ORDERED, LabOrder.Status.COLLECTED,
                LabOrder.Status.IN_PROGRESS).contains(o.getStatus())).toList();
        if (!pending.isEmpty()) {
            b.add("Pending investigations: " + pending.stream().map(o -> o.getTestName() + " (" + o.getStatus().name().toLowerCase() + ")")
                            .collect(Collectors.joining(", ")),
                    pending.stream().map(o -> src("LAB_ORDER", o.getId(), o.getOrderNumber(), o.getOrderedAt())).toList());
        }

        List<MedicationOrder> active = medOrders.findByAdmissionIdAndStatusIn(a.getId(), EnumSet.of(MedicationOrder.Status.ACTIVE,
                MedicationOrder.Status.ON_HOLD));
        if (!active.isEmpty()) {
            Map<UUID, Medication> meds = medications.findByIdIn(active.stream().map(MedicationOrder::getMedicationId).toList()).stream()
                    .collect(Collectors.toMap(Medication::getId, Function.identity()));
            b.add("Current medications: " + active.stream().map(o -> {
                        Medication m = meds.get(o.getMedicationId());
                        return (m == null ? "?" : m.getGenericName()) + " " + o.getDose() + " " + o.getDoseUnit() + " " + o.getRoute() + " "
                                + o.getFrequency() + (o.getStatus() == MedicationOrder.Status.ON_HOLD ? " (on hold)" : "");
                    }).collect(Collectors.joining("; ")),
                    active.stream().map(o -> src("MEDICATION_ORDER", o.getId(), "Order", o.getPrescribedAt())).toList());
        }
        List<MedicationAdministration> exceptions = administrations.findByAdmissionIdAndScheduledAtBetweenOrderByScheduledAtAsc(a.getId(), day, now)
                .stream().filter(m -> m.getStatus().isException()).toList();
        if (!exceptions.isEmpty()) {
            b.add(exceptions.size() + " medication exception(s) in the last 24 h: " + exceptions.stream().limit(4)
                            .map(m -> m.getStatus().name().toLowerCase() + " at " + f.format(m.getScheduledAt()) + " (" + m.getReason() + ")")
                            .collect(Collectors.joining("; ")),
                    exceptions.stream().map(m -> src("MEDICATION_ADMINISTRATION", m.getId(), m.getStatus().name(), m.getScheduledAt())).toList());
        }

        notes.findByAdmissionIdOrderByAuthoredAtDesc(a.getId()).stream()
                .filter(n -> n.getStatus() == ClinicalNote.Status.FINAL && n.getAuthoredAt().isAfter(day))
                .filter(n -> type == AiDraft.DraftType.HANDOVER ? n.getNoteType().isNursing() : true)
                .limit(2)
                .forEach(n -> b.add("Documented in " + ClinicalRecordService.humanType(n.getNoteType()).toLowerCase() + " ("
                                + f.format(n.getAuthoredAt()) + "): " + ClinicalSupport.truncate(n.getAssessment() != null ? n.getAssessment() : n.getContent(), 240),
                        List.of(src("CLINICAL_NOTE", n.getId(), n.getTitle(), n.getAuthoredAt()))));

        List<CareTask> open = tasks.findByAdmissionIdAndStatusIn(a.getId(), CareTaskService.ACTIVE);
        if (!open.isEmpty()) {
            b.add(open.size() + " open care task(s): " + open.stream().limit(4).map(CareTask::getTitle).collect(Collectors.joining("; ")),
                    open.stream().map(t -> src("CARE_TASK", t.getId(), t.getTitle(), t.getCreatedAt())).toList());
        }
        if (a.getExpectedDischargeDate() != null) {
            b.add("Expected discharge date: " + a.getExpectedDischargeDate(),
                    List.of(src("ADMISSION", a.getId(), "Expected discharge", null)));
        }
    }

    @Transactional(readOnly = true)
    public List<DraftView> forAdmission(UUID admissionId) {
        support.requireClinical(admissionId);
        return drafts.findByAdmissionIdOrderByCreatedAtDesc(admissionId).stream().map(this::view).toList();
    }

    @Transactional
    public DraftView accept(UUID draftId, String title, String editedContent) {
        AiDraft d = support.requireOrg(drafts.findById(draftId), "Draft");
        Admission a = support.requireOpenClinical(d.getAdmissionId());
        if (d.getStatus() != AiDraft.Status.DRAFT) {
            throw ApiException.rule("DRAFT_CLOSED", "This draft has already been " + d.getStatus().name().toLowerCase() + ".");
        }
        CurrentUser u = TenantContext.requireUser();
        ClinicalNote.NoteType type = u.role() == Role.NURSE ? ClinicalNote.NoteType.NURSING_OBSERVATION : ClinicalNote.NoteType.PROGRESS;
        String content = ClinicalSupport.blankToNull(editedContent) != null ? editedContent.trim() : d.getContent();
        String t = ClinicalSupport.blankToNull(title) != null ? title.trim()
                : (d.getDraftType() == AiDraft.DraftType.HANDOVER ? "Handover summary" : "Progress summary") + " (reviewed draft)";
        NoteView note = records.addNote(a.getId(), new NoteRequest(type, t, null, null, null, null,
                content + "\n\n[Reviewed and accepted by " + u.fullName() + " from draft generated by " + GENERATOR + "]", null));
        d.setStatus(AiDraft.Status.ACCEPTED);
        d.setReviewedBy(u.userId());
        d.setReviewedAt(Instant.now());
        d.setPublishedNoteId(note.id());
        audit.record("DRAFT_ACCEPTED", "AI_DRAFT", d.getId(), a.getPatientId(), "Published as note " + note.id()
                + (Objects.equals(content, d.getContent()) ? "" : " (edited)"));
        drafts.flush();
        return view(d);
    }

    @Transactional
    public DraftView reject(UUID draftId, String reason) {
        AiDraft d = support.requireOrg(drafts.findById(draftId), "Draft");
        Admission a = support.requireClinical(d.getAdmissionId());
        if (d.getStatus() != AiDraft.Status.DRAFT) {
            throw ApiException.rule("DRAFT_CLOSED", "This draft has already been " + d.getStatus().name().toLowerCase() + ".");
        }
        d.setStatus(AiDraft.Status.REJECTED);
        d.setReviewedBy(TenantContext.actorId());
        d.setReviewedAt(Instant.now());
        audit.record("DRAFT_REJECTED", "AI_DRAFT", d.getId(), a.getPatientId(), reason);
        drafts.flush();
        return view(d);
    }

    DraftView view(AiDraft d) {
        Map<UUID, String> names = support.userNames(List.of(d.getCreatedBy(), d.getReviewedBy() == null ? d.getCreatedBy() : d.getReviewedBy()));
        return new DraftView(d.getId(), d.getAdmissionId(), d.getDraftType(), d.getGenerator(), d.getContent(), d.getSourceRefs(),
                d.getStatus(), names.get(d.getCreatedBy()), d.getCreatedAt(), names.get(d.getReviewedBy()), d.getReviewedAt(),
                d.getPublishedNoteId(), DISCLAIMER);
    }
}
